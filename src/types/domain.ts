/** Role ranking used by `requireRole`. Higher wins. */
export const ROLE_RANK: Record<UserRole, number> = {
  reader: 0,
  analyst: 10,
  contributor: 20,
  writer: 30,
  media_manager: 40,
  editor: 50,
  commercial_manager: 50,
  managing_editor: 70,
  owner: 100,
};

export function roleAtLeast(role: UserRole, minimum: UserRole): boolean {
  return ROLE_RANK[role] >= ROLE_RANK[minimum];
}

export function highestUserRole(values: readonly unknown[]): UserRole {
  return values.reduce<UserRole>((highest, value) => {
    if (!isUserRole(value)) return highest;
    return roleAtLeast(value, highest) ? value : highest;
  }, "reader");
}
