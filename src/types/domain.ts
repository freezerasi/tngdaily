/**
 * What a visual *is*, as opposed to where the file came from.
 *
 * `ImageSource` above records the upload origin (a Cloudinary upload, a Pexels
 * result). This records the editorial status of the frame, which is the thing a
 * reader needs to know: whether they are looking at evidence, an illustration,
 * or a development placeholder.
 */
export const MEDIA_SOURCE_TYPES = [
  /** Photographed by us or a named contributor at the place described. */
  "original_photo",
  /** Stock or wire photo under licence, credited to its photographer. */
  "licensed_photo",
  /** Sent in by a reader, with consent recorded. */
  "community_submission",
  /** Map, chart, diagram, or other authored graphic. */
  "editorial_graphic",
  /** Generated by a model. Never evidence of anything. */
  "ai_illustration",
  /** Development placeholder. Must never reach production. */
  "mock_visual",
] as const;
export type MediaSourceType = (typeof MEDIA_SOURCE_TYPES)[number];

/**
 * Provenance travels with every visual. The three booleans exist so a template
 * never has to infer intent from the credit string: a caption generator, an
 * indexer, or a reviewer can ask directly whether a frame claims to show a real
 * place or a real event.
 */
export interface MediaProvenance {
  sourceType: MediaSourceType;
  /** Shown to readers. Must not claim reporting that did not happen. */
  credit: string;
  /** True when the frame illustrates an idea rather than documenting a fact. */
  isIllustrative: boolean;
  depictsActualLocation: boolean;
  depictsActualEvent: boolean;
  /** Reader-facing sentence, rendered under the image when present. */
  disclosure: string | null;
}

export function isMediaSourceType(value: unknown): value is MediaSourceType {
  return (
    typeof value === "string" &&
    (MEDIA_SOURCE_TYPES as readonly string[]).includes(value)
  );
}

